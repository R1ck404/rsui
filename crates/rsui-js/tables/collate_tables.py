"""Makes `src/builtins/collate_tables.rs` from CLDR's root collation, `allkeys_CLDR.txt`.

Run it as `python tables/collate_tables.py allkeys_CLDR.txt` from `crates/rsui-js`, with the file from
https://github.com/unicode-org/cldr/blob/release-48/common/uca/allkeys_CLDR.txt (the CLDR that Edge's and Node's ICU
use). Han and the other characters whose weights the standard works out from the code point aren't in it, as
they aren't in the file. Letters with accents are, so that text without combining marks needn't be taken apart.
"""

import re
import sys
import unicodedata

MAX_RUN = 2048


def element(variable, primary, secondary, tertiary):
    # One collation element in 31 bits: whether it's variable (punctuation, spaces and symbols), then the three weights.
    assert primary < 1 << 16 and secondary < 1 << 9 and tertiary < 1 << 5
    return (variable << 30) | (primary << 14) | (secondary << 5) | tertiary


def main():
    singles = {}
    contractions = {}
    for line in open(sys.argv[1], encoding='utf-8'):
        line = line.split('#')[0].strip()
        if not line or line.startswith('@'):
            continue
        left, right = line.split(';')
        points = tuple(int(x, 16) for x in left.split())
        elements = [element(m.group(1) == '*', int(m.group(2), 16), int(m.group(3), 16), int(m.group(4), 16))
                    for m in re.finditer(r'\[([.*])([0-9A-F]{4})\.([0-9A-F]{4})\.([0-9A-F]{4})\]', right)]
        if len(points) == 1:
            singles[points[0]] = elements
        else:
            contractions[points] = elements

    expansions = []

    def expansion(elements):
        offset = len(expansions)
        expansions.extend(elements)
        assert len(elements) < 256 and offset < 1 << 23
        return (1 << 31) | (offset << 8) | len(elements)

    def han_alias(elements):
        # A character that collates as one Han character, as the compatibility ideographs and the circled and squared
        # ones do: it's kept as that character and the tertiary weight, as Han's weights are worked out from its place
        # in radical-stroke order (`collate_han.rs`) rather than from its code point, as the file has them.
        if len(elements) != 2:
            return None
        lead, rest = elements
        lead_primary = lead >> 14 & 0xFFFF
        if not 0xFB40 <= lead_primary < 0xFBC0 or rest & 0x3FFF != 0:
            return None
        base = 0xFB40 if lead_primary < 0xFB80 else 0xFB80
        target = (lead_primary - base) << 15 | (rest >> 14 & 0x7FFF)
        assert target < 1 << 18
        return (1 << 31) | ((lead & 0x1F) << 26) | (target << 8)

    starts = []
    values = []
    previous = None
    for point in sorted(singles):
        elements = singles[point]
        alias = han_alias(elements)
        if alias is not None:
            previous = [point, 1, alias]
            starts.append(previous)
            continue
        if len(elements) == 1:
            value = elements[0]
            if (previous is not None and previous[0] + previous[1] == point and previous[1] < MAX_RUN
                    and previous[2] + (previous[1] << 14) == value and value >> 14 & 0xFFFF != 0):
                previous[1] += 1
                continue
            previous = [point, 1, value]
        else:
            previous = [point, 1, expansion(elements)]
        starts.append(previous)
    runs = [(point << 11 | (length - 1), value) for point, length, value in starts]

    pairs = []
    for points, elements in sorted(contractions.items()):
        value = elements[0] if len(elements) == 1 else expansion(elements)
        pairs.append((points[0], points[1], points[2] if len(points) > 2 else 0, value))

    zeros = sorted(point for point in range(0x110000)
                   if unicodedata.category(chr(point)) == 'Nd' and unicodedata.decimal(chr(point)) == 0)

    def table(values, per_line=10):
        lines = []
        for at in range(0, len(values), per_line):
            lines.append('    ' + ' '.join(f'0x{value:X},' for value in values[at:at + per_line]))
        return '\n'.join(lines)

    out = open('src/builtins/collate_tables.rs', 'w', encoding='utf-8', newline='\r\n')
    out.write('//! Generated by `tables/collate_tables.py` from CLDR 48\'s root collation (`allkeys_CLDR.txt`, UCA 17.0.0).\n')
    out.write("//! Don't edit this by hand.\n")
    out.write('//!\n')
    out.write('//! A collation element is 31 bits: whether it is variable at bit 30, the primary weight above bit 14, the\n')
    out.write('//! secondary above bit 5 and the tertiary below it.\n\n')
    out.write('/// Runs of code points, sorted: the first code point of each, shifted up 11, and how many follow it in the bits\n')
    out.write('/// below. Each code point of a run has the element of the one before it with a primary one more.\n')
    out.write('pub(crate) const RUN_STARTS: &[u32] = &[\n' + table([start for start, _ in runs]) + '\n];\n\n')
    out.write('/// The element of the first code point of each run; or, with the top bit set, where its elements start in\n')
    out.write('/// `EXPANSIONS`, shifted up 8, and how many there are in the bits below. With none, it collates as the Han\n')
    out.write('/// character in bits 8 to 25, with the tertiary weight in bits 26 to 30.\n')
    out.write('pub(crate) const RUN_VALUES: &[u32] = &[\n' + table([value for _, value in runs]) + '\n];\n\n')
    out.write('/// The elements of characters that have more than one.\n')
    out.write('pub(crate) const EXPANSIONS: &[u32] = &[\n' + table(expansions) + '\n];\n\n')
    out.write('/// Sequences of two or three code points that collate as one, sorted, with their elements as in `RUN_VALUES`.\n')
    out.write('/// The third code point is 0 for pairs.\n')
    out.write('pub(crate) const CONTRACTIONS: &[(u32, u32, u32, u32)] = &[\n')
    for first, second, third, value in pairs:
        out.write(f'    (0x{first:X}, 0x{second:X}, 0x{third:X}, 0x{value:X}),\n')
    out.write('];\n\n')
    out.write('/// The zero of every set of decimal digits, which go up from it to nine.\n')
    out.write('pub(crate) const DIGIT_ZEROS: &[u32] = &[\n' + table(zeros) + '\n];\n')
    print('runs', len(runs), 'expansions', len(expansions), 'contractions', len(pairs), 'zeros', len(zeros))


main()
