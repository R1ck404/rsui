// Makes `src/builtins/collate_han.rs`: the order of the common Han characters, as Node's ICU (Edge's) has them. CLDR's
// root collation puts Han in radical-stroke order (Unihan's kRSUnicode), which isn't the order of the code points, so
// it's read off ICU here. Run it from `crates/rsui-js`: `node tables/collate_han.js`.
'use strict';
const fs = require('fs');

// The main block, Extension A, and the twelve unified ideographs among the compatibility ones. The other extensions
// are rare enough in names that they go after these, by code point.
const points = [];
for (let point = 0x3400; point <= 0x4dbf; point += 1) points.push(point);
for (let point = 0x4e00; point <= 0x9fff; point += 1) points.push(point);
points.push(0xfa0e, 0xfa0f, 0xfa11, 0xfa13, 0xfa14, 0xfa1f, 0xfa21, 0xfa23, 0xfa24, 0xfa27, 0xfa28, 0xfa29);

const collator = new Intl.Collator('en');
const ordered = [...points].sort((a, b) => collator.compare(String.fromCodePoint(a), String.fromCodePoint(b)) || a - b);
const rank = new Map(ordered.map((point, at) => [point, at]));
// Runs of code points one after another whose ranks are one after another too.
const runs = [];
for (const point of points) {
    const last = runs[runs.length - 1];
    if (last && last.end + 1 === point && rank.get(last.end) + 1 === rank.get(point)) {
        last.end = point;
    } else {
        runs.push({ start: point, end: point });
    }
}
const words = runs.map(({ start }) => `0x${(((start << 16) | rank.get(start)) >>> 0).toString(16).toUpperCase()},`);
const lines = [];
for (let at = 0; at < words.length; at += 10) lines.push('    ' + words.slice(at, at + 10).join(' '));
const out = [
    `//! Generated by \`tables/collate_han.js\` from ICU ${process.versions.icu}. Don't edit this by hand.`,
    '',
    '/// The radical-stroke order of the common Han characters, as runs: the first code point of each, shifted up 16, and',
    '/// its place in the order in the bits below. Each code point of a run comes just after the one before it.',
    'pub(crate) const HAN_RUNS: &[u32] = &[',
    ...lines,
    '];',
    '',
];
fs.writeFileSync('src/builtins/collate_han.rs', out.join('\r\n'));
console.log(runs.length, 'runs of', points.length, 'characters');
