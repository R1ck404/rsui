function inRanges(table: number[], cp: number): boolean {
    let low = 0;
    let high = table.length / 2 - 1;
    while (low <= high) {
        const mid = (low + high) >> 1;
        if (cp < table[mid * 2]) high = mid - 1;
        else if (cp > table[mid * 2 + 1]) low = mid + 1;
        else return true;
    }
    return false;
}

/** The cells a character takes. */
export function cellWidth(cp: number): number {
    if (cp < 0x300) return cp < 0x20 || (cp >= 0x7f && cp < 0xa0) ? 0 : 1;
    if (inRanges(ZERO, cp)) return 0;
    if (cp >= 0x1100 && inRanges(WIDE, cp)) return 2;
    return 1;
}

/** Characters that are one cell as text but two when the variation selector FE0F follows. */
export function widensWithEmojiSelector(cp: number): boolean {
    return (
        cp === 0xa9 || cp === 0xae || cp === 0x203c || cp === 0x2049 || cp === 0x2122 || cp === 0x2139 ||
        (cp >= 0x2194 && cp <= 0x21aa) || (cp >= 0x2300 && cp <= 0x23ff) || (cp >= 0x24c2 && cp <= 0x24c2) ||
        (cp >= 0x25aa && cp <= 0x25fe) || (cp >= 0x2600 && cp <= 0x27bf) || (cp >= 0x2934 && cp <= 0x2935) ||
        (cp >= 0x2b05 && cp <= 0x2b55) || cp === 0x3030 || cp === 0x303d || cp === 0x3297 || cp === 0x3299 ||
        (cp >= 0x1f170 && cp <= 0x1f251) || (cp >= 0x1f300 && cp <= 0x1faff)
    );
}
